class CelestialBody:
    def __init__(
        self,
        id: str,
        name: str,
        body_type: str,
        is_planet: bool,
        mass: str,
        radius: str,
        dist: str,
        hab: str,
        size: float,
        is_disc: bool,
        is_star: bool,
        photo: str,
        tex: str = None,
        ringTex: str = None,
        starColor: int = None,
        ra: float = None,
        dec: float = None,
        mag: float = None,
    ):
        self.id = id
        self.name = name
        self.body_type = body_type
        self.is_planet = is_planet
        self.mass = mass
        self.radius = radius
        self.dist = dist
        self.hab = hab
        self.size = size
        self.is_disc = is_disc
        self.is_star = is_star
        self.photo = photo
        self.tex = tex
        self.ringTex = ringTex
        self.starColor = starColor
        self.ra = ra
        self.dec = dec
        self.mag = mag


